#!/usr/bin/env python3
"""Live long-tail game E2E against a deployed VibeForge instance.

Usage:
    VIBEFORGE_E2E_BASE=https://117.148.166.55:12888 .venv/bin/python tests/e2e_game_live.py
"""
from __future__ import annotations

import json
import os
import tempfile
import time
from pathlib import Path

from playwright.sync_api import sync_playwright

BASE = os.environ.get("VIBEFORGE_E2E_BASE", "").rstrip("/")
if not BASE:
    raise SystemExit("VIBEFORGE_E2E_BASE is required")
ARTIFACTS = Path(tempfile.mkdtemp(prefix="vibeforge-game-live-"))


def check(condition: bool, message: str) -> None:
    if not condition:
        raise AssertionError(message)
    print(f"  ok  {message}")


def post_json(request, path: str, payload: dict):
    return request.post(
        BASE + path,
        data=json.dumps(payload),
        headers={"Content-Type": "application/json"},
    )


def main() -> int:
    username = "game_e2e_" + str(int(time.time()))
    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(channel="chrome", headless=True)
        context = browser.new_context(
            viewport={"width": 1280, "height": 900}, ignore_https_errors=True
        )
        request = context.request
        register = post_json(
            request,
            "/api/auth/register",
            {"username": username, "password": "game-e2e-password", "display_name": "Game E2E"},
        )
        check(register.status == 200, "register live test user")

        created = post_json(
            request,
            "/api/projects",
            {
                "prompt": "做一个 2048 数字合并小游戏：方向键和手机触控都能玩，显示分数、暂停和重新开始",
                "capability": "game",
            },
        )
        check(created.status == 200, "create long-tail game")
        task = created.json()["task"]
        project_id = task["id"]
        check(task["stack"] == "static", "game stays on the static path")

        deadline = time.time() + 360
        events: list[dict] = []
        while time.time() < deadline:
            detail = request.get(BASE + f"/api/projects/{project_id}").json()
            task = detail["task"]
            events = detail.get("events", [])
            if task["status"] == "error":
                raise AssertionError(f"game failed: {task.get('error')}")
            if task["status"] == "done":
                break
            time.sleep(1)
        check(task.get("status") == "done", "game project completed")

        html = request.get(BASE + f"/p/{project_id}/").text()
        custom = 'name="vibeforge-game"' in html
        fallback = "vibeforge-snake-best" in html
        check("<canvas" in html, "generated page has a canvas")
        check("<script" in html, "generated page has an inline script")
        check(custom or fallback, f"game path resolved (custom={custom}, fallback={fallback})")
        if custom:
            print("  info custom game generated by the LLM and passed validation")
        else:
            print("  info LLM output failed validation; built-in engine fallback used")

        thinking = [event for event in events if event.get("type") == "thinking"]
        check(
            any("自定义玩法" in str(event.get("step", "")) for event in thinking),
            "agent narrated the game spec",
        )

        share = task.get("share_url")
        check(bool(share), "public link issued")
        anonymous = browser.new_context(ignore_https_errors=True)
        check(anonymous.request.get(BASE + str(share)).status == 200, "public game page 200")

        page = context.new_page()
        errors: list[str] = []
        page.on("pageerror", lambda error: errors.append(str(error)))
        page.goto(BASE + f"/p/{project_id}/", wait_until="networkidle")
        check(page.locator("canvas").count() > 0, "browser renders the game canvas")
        before = page.locator("canvas").first.evaluate("(c) => c.toDataURL().slice(0, 200)")
        page.keyboard.press("ArrowRight")
        page.wait_for_timeout(400)
        after = page.locator("canvas").first.evaluate("(c) => c.toDataURL().slice(0, 200)")
        print(f"  info canvas frame changed: {before != after}")
        check(not errors, f"no page errors ({errors[:2]})")
        page.screenshot(path=str(ARTIFACTS / "live-game.png"), full_page=True)
        browser.close()

    print(f"\nLIVE GAME E2E PASSED\nartifacts: {ARTIFACTS}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
